using System.IO;
using System.Security.Cryptography;
using System.Text;
using SoulspireLauncher.Models;

namespace SoulspireLauncher.Services;

/// <summary>
/// Generates isolated Modern (VanaCore / Soulspire Client) configuration and boot scripts under
/// ModernClient\baseline\ and ModernClient\compat\ without ever mutating Ashita\ or retail FFXI Game\
/// files, and without ever persisting plaintext passwords to disk.
/// </summary>
public sealed class ModernClientConfigGenerator
{
    public const string DefaultIniFileName = "vanacore.ini";
    public const string BootScriptRelativePath = @"scripts\boot.txt";
    public const string RollbackFolderName = ".rollback";

    public static bool IsModernEngine(ClientEngineMode mode) =>
        mode is ClientEngineMode.ModernBaseline or ClientEngineMode.ModernCompat or ClientEngineMode.ModernNative;

    public static string GetProfileFolderName(ClientEngineMode mode) => mode switch
    {
        ClientEngineMode.ModernNative => "native",
        ClientEngineMode.ModernCompat => "compat",
        _ => "baseline"
    };

    public static string ResolveProfileDirectory(string modernClientRoot, ClientEngineMode mode)
    {
        var root = string.IsNullOrWhiteSpace(modernClientRoot)
            ? Path.Combine(AppContext.BaseDirectory, "ModernClient")
            : modernClientRoot.Trim();
        return Path.Combine(root, GetProfileFolderName(mode));
    }

    public static ClientEngineMode ResolveEffectiveEngine(LauncherSettings settings, LauncherManifest? manifest)
    {
        if (!IsModernEngine(settings.ClientEngine))
        {
            return ClientEngineMode.Classic;
        }

        var normalizedChannel = ManifestUpdateService.NormalizeUserFacingChannel(settings.UpdateChannel);
        var pkg = manifest?.ModernClient?.ResolvePackage(settings.ClientEngine);

        if (normalizedChannel == UpdateChannel.Stable)
        {
            return pkg?.ClientVerified == true
                ? settings.ClientEngine
                : ClientEngineMode.Classic;
        }

        // Testing channel: enforce explicit experimental eligibility policy when manifest declares modernClient.
        if (manifest?.ModernClient is not null)
        {
            return pkg is not null && (pkg.ClientVerified || pkg.ExperimentalEligible)
                ? settings.ClientEngine
                : ClientEngineMode.Classic;
        }

        return settings.ClientEngine;
    }

    public static string GetAccountIniFileName(string? username)
    {
        if (string.IsNullOrWhiteSpace(username))
        {
            return DefaultIniFileName;
        }

        var normalized = username.Trim().ToLowerInvariant();
        var hash = SHA256.HashData(Encoding.UTF8.GetBytes(normalized));
        var prefix = Convert.ToHexString(hash)[..12].ToLowerInvariant();
        return $"vanacore.{prefix}.ini";
    }

    public bool LastGamepadImportSucceeded { get; private set; }
    public string LastGamepadImportDiagnostic { get; private set; } = string.Empty;

    public static string BuildIniContent(
        LauncherSettings settings,
        ClientEngineMode mode,
        string serverHost,
        string? polFolder,
        string? ffxiFolder,
        FfxiGamepadConfig? gamepadConfig = null)
    {
        var isBaseline = mode == ClientEngineMode.ModernBaseline;
        var isNative = mode == ClientEngineMode.ModernNative;
        var sb = new StringBuilder();
        var profileLabel = mode switch
        {
            ClientEngineMode.ModernBaseline => "Modern — VanaCore Baseline",
            ClientEngineMode.ModernNative => "Modern — Soulspire Native (Zero Ashita Compat)",
            _ => "Modern — Soulspire Compatibility"
        };
        sb.AppendLine($"; Auto-generated by SoulspireXI Launcher for {profileLabel}.");
        sb.AppendLine("; SECURITY: Passwords are NEVER written to this file (passed via --password-stdin or hidden prompt).");
        sb.AppendLine();

        sb.AppendLine("[server]");
        sb.AppendLine($"server={serverHost.Trim()}");
        sb.AppendLine();

        sb.AppendLine("[client]");
        if (!string.IsNullOrWhiteSpace(polFolder))
        {
            sb.AppendLine($"pol={polFolder.Trim()}");
        }
        if (!string.IsNullOrWhiteSpace(ffxiFolder))
        {
            sb.AppendLine($"ffxi={ffxiFolder.Trim()}");
        }
        sb.AppendLine("attached=0");
        sb.AppendLine($"autoclose={(settings.AutoCloseOnLaunch ? 1 : 0)}");
        // Keep singlemenu=0 so menuwind Button ID 16 stays owned by Soulspire Native (BLK-013).
        sb.AppendLine("singlemenu=0");
        if (isBaseline)
        {
            // Baseline profile disables experimental menu/UI hooks for clean first-login verification.
            sb.AppendLine("configmenu=0");
            sb.AppendLine("gamesettings.extended=0");
            sb.AppendLine("partyfinder.findmember=0");
            sb.AppendLine("macrooptions.equipfirst=0");
            sb.AppendLine("blink.disable=0");
        }
        else
        {
            sb.AppendLine("packets.keepactions=1");
        }
        sb.AppendLine();

        sb.AppendLine("[logging]");
        sb.AppendLine("enabled=1");
        sb.AppendLine();

        sb.AppendLine("[addons]");
        sb.AppendLine($"ashita.enabled={(isNative ? 0 : 1)}");
        sb.AppendLine("ashita.interface=4.30");
        sb.AppendLine("ashita.libs=4.30");
        sb.AppendLine("delay.login=1");
        sb.AppendLine();

        sb.AppendLine("[pivot]");
        // Mandatory SoulspireXI DAT overlays (base soulspirexi + protected COR Flintlock dual pistols)
        // are always enabled in non-baseline VanaCore profiles (CLIENT-ADDON-001).
        var enablePivot = !isBaseline;
        sb.AppendLine($"enabled={(enablePivot ? 1 : 0)}");
        sb.AppendLine("rootfolder=pivot");
        if (enablePivot)
        {
            sb.AppendLine();
            sb.AppendLine("[pivot.order]");
            sb.AppendLine("0=soulspirexi");
            sb.AppendLine($"1={AshitaConfigGenerator.FlintlockOverlayFolderName}");
        }
        sb.AppendLine();

        sb.AppendLine("[graphics]");
        sb.AppendLine($"renderer={(settings.ModernClientUseD3D11Fallback ? "d3d11" : "d3d12")}");
        sb.AppendLine();

        var ffxiWindowMode = settings.WindowMode switch
        {
            WindowModeOption.Windowed => "windowed",
            WindowModeOption.Fullscreen => "fullscreen",
            _ => "borderless fullscreen"
        };
        sb.AppendLine("[ffxi]");
        sb.AppendLine($"mode={ffxiWindowMode}");
        sb.AppendLine($"resolution.game={Math.Max(640, settings.WindowWidth)}x{Math.Max(480, settings.WindowHeight)}");
        sb.AppendLine($"resolution.ui={Math.Max(640, settings.MenuWidth)}x{Math.Max(480, settings.MenuHeight)}");
        sb.AppendLine($"hardwaremouse={(settings.HardwareMouse ? 1 : 0)}");

        var effectivePadMode = NormalizeGamepadValue(gamepadConfig?.PadMode) ?? NormalizeGamepadValue(settings.PadMode);
        var effectivePadSin = NormalizeGamepadValue(gamepadConfig?.PadSin) ?? NormalizeGamepadValue(settings.PadSin);
        var effectivePadExSin = NormalizeGamepadValue(gamepadConfig?.PadExSin) ?? NormalizeGamepadValue(settings.PadExSin);
        var effectivePadGuid = NormalizeGamepadValue(gamepadConfig?.PadGuid) ?? NormalizeGamepadValue(settings.PadGuid);
        var padSource = !string.IsNullOrWhiteSpace(gamepadConfig?.Source)
            ? gamepadConfig!.Source
            : (effectivePadMode is not null || effectivePadSin is not null || effectivePadExSin is not null || effectivePadGuid is not null
                ? "LauncherSettings"
                : "Not found — VanaCore defaults");

        sb.AppendLine($"; gamepad.source={padSource}");
        if (effectivePadMode is not null)
        {
            sb.AppendLine($"gamepad.mode={effectivePadMode}");
        }
        if (effectivePadSin is not null)
        {
            sb.AppendLine($"gamepad.buttons={effectivePadSin}");
        }
        if (effectivePadExSin is not null)
        {
            sb.AppendLine($"gamepad.buttons_ex={effectivePadExSin}");
        }
        if (effectivePadGuid is not null)
        {
            sb.AppendLine($"gamepad.guid={effectivePadGuid}");
        }
        sb.AppendLine();

        if (settings.GamepadDisableEnumeration)
        {
            sb.AppendLine("[input]");
            sb.AppendLine("gamepad.disableenumeration=1");
            sb.AppendLine();
        }

        sb.AppendLine("[discord]");
        sb.AppendLine("enabled=0");
        sb.AppendLine();
        sb.AppendLine("[mcp]");
        sb.AppendLine("available=0");
        sb.AppendLine("enabled=0");
        sb.AppendLine();
        sb.AppendLine("[developer]");
        sb.AppendLine("enabled=0");
        sb.AppendLine();
        sb.AppendLine("[soulspire]");
        sb.AppendLine($"enabled={(isBaseline ? 0 : 1)}");

        return sb.ToString();
    }

    public static string BuildBootScriptContent(LauncherSettings settings, ClientEngineMode mode)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Auto-generated by SoulspireXI Launcher for Modern Client (VanaCore).");
        if (mode == ClientEngineMode.ModernBaseline)
        {
            sb.AppendLine("# Modern — VanaCore Baseline: all custom Soulspire native hooks, addons & menu mods disabled.");
            return sb.ToString();
        }

        if (mode == ClientEngineMode.ModernNative)
        {
            sb.AppendLine("# Modern — Soulspire Native: pure VanaCore-native Soulspire engine ([soulspire] enabled=1, [addons] ashita.enabled=0).");
            sb.AppendLine("# Loads EXACTLY ONE unified VanaCore-native Soulspire Core addon with zero Ashita compatibility fallback (DEC-028).");
            sb.AppendLine("/wait 1");
            sb.AppendLine("/addon load soulspire_core vanacore");
            if (settings.AutoLoadBattleLensAddon)
            {
                sb.AppendLine("/addon load battlelens vanacore");
                sb.AppendLine("/wait 1");
                sb.AppendLine("/battlelens launcher-on");
            }
            return sb.ToString();
        }

        sb.AppendLine("# Modern — Soulspire Compatibility: VanaCore-native Soulspire engine ([soulspire] enabled=1) & full polished UI boot script.");
        sb.AppendLine("# Legacy external soulspire_native.dll is intentionally omitted so VanaCore's coordinated src/core/soulspire/ owns hooks + native Commands menu (DEC-028).");
        sb.AppendLine("/wait 1");
        if (settings.AutoLoadCrystalSocketAddon)
        {
            sb.AppendLine("/addon load crystalsocket ashita");
        }
        if (settings.AutoLoadKazenoeyeAddon)
        {
            sb.AppendLine("/addon load kazenoeye ashita");
        }
        if (settings.AutoLoadSoulHudAddon)
        {
            sb.AppendLine("/addon load soulspire_soulhud ashita");
        }
        if (settings.AutoLoadSoulHudAddon || settings.AutoLoadTalentsAddon)
        {
            sb.AppendLine("/addon load soulspire_core ashita");
        }
        if (settings.AutoLoadFlintlockAddon)
        {
            sb.AppendLine("/addon load soulspire_flintlock ashita");
        }
        if (settings.AutoLoadGearAddon)
        {
            sb.AppendLine("/addon load soulspire_gear ashita");
        }
        sb.AppendLine("/addon load soulspire_soul_actions ashita");
        return sb.ToString();
    }

    private static string? NormalizeGamepadValue(string? raw)
    {
        if (string.IsNullOrWhiteSpace(raw))
        {
            return null;
        }

        var trimmed = raw.Trim();
        return trimmed == "-1" ? null : trimmed;
    }

    public string WriteAllConfigs(
        string modernProfileDir,
        LauncherSettings settings,
        ClientEngineMode mode,
        string serverHost,
        string? polFolder,
        string? ffxiFolder,
        FfxiGamepadConfig? explicitGamepadConfig = null)
    {
        Directory.CreateDirectory(modernProfileDir);
        Directory.CreateDirectory(Path.Combine(modernProfileDir, "scripts"));
        Directory.CreateDirectory(Path.Combine(modernProfileDir, "pivot"));
        Directory.CreateDirectory(Path.Combine(modernProfileDir, "logs"));

        var iniFileName = GetAccountIniFileName(settings.Username);
        var iniPath = Path.Combine(modernProfileDir, iniFileName);
        var bootPath = Path.Combine(modernProfileDir, BootScriptRelativePath);

        // Preserve existing customized [ffxi] gamepad.* bindings in vanacore.ini across updates/relaunches;
        // otherwise non-destructively import the player's real FFXI controller config (Registry / Ashita).
        FfxiGamepadConfig? resolvedGamepad = explicitGamepadConfig;
        if (resolvedGamepad is null && File.Exists(iniPath))
        {
            try
            {
                resolvedGamepad = SettingsImportService.ParseVanaCoreIniGamepadConfig(File.ReadAllText(iniPath, Encoding.UTF8));
            }
            catch
            {
                // Fall back to fresh non-destructive import below.
            }
        }

        if (resolvedGamepad is null)
        {
            var importer = new SettingsImportService();
            resolvedGamepad = importer.ReadBestExistingGamepadConfig(settings);
        }

        LastGamepadImportSucceeded = resolvedGamepad.HasAny;
        LastGamepadImportDiagnostic = resolvedGamepad.HasAny
            ? $"FFXI controller config inherited ({resolvedGamepad.Source}): mode={(resolvedGamepad.PadMode is not null ? "set" : "unset")}, buttons={(resolvedGamepad.PadSin is not null ? "set" : "unset")}, guid={(resolvedGamepad.PadGuid is not null ? "set" : "unset")}."
            : $"FFXI controller config not found ({resolvedGamepad.Source}); VanaCore will use default gamepad settings until configured.";

        File.WriteAllText(iniPath, BuildIniContent(settings, mode, serverHost, polFolder, ffxiFolder, resolvedGamepad), new UTF8Encoding(false));
        File.WriteAllText(bootPath, BuildBootScriptContent(settings, mode), new UTF8Encoding(false));
        return iniFileName;
    }

    /// <summary>
    /// Snapshots existing ModernClient executables/DLLs to .rollback\ before updates
    /// so players can roll back cleanly without touching Classic Ashita v4.
    /// </summary>
    public static int CreateRollbackSnapshot(string modernProfileDir)
    {
        if (string.IsNullOrWhiteSpace(modernProfileDir) || !Directory.Exists(modernProfileDir))
        {
            return 0;
        }

        var rollbackDir = Path.Combine(modernProfileDir, RollbackFolderName);
        if (Directory.Exists(rollbackDir))
        {
            Directory.Delete(rollbackDir, recursive: true);
        }
        Directory.CreateDirectory(rollbackDir);

        var copied = 0;
        foreach (var name in new[] { "SoulspireClient.exe", "VanaCore.exe", "SoulspireClient.Core.dll", "VanaCore.Core.dll", "build-provenance.json" })
        {
            var src = Path.Combine(modernProfileDir, name);
            if (File.Exists(src))
            {
                File.Copy(src, Path.Combine(rollbackDir, name), overwrite: true);
                copied++;
            }
        }
        return copied;
    }

    public static int RestoreRollbackSnapshot(string modernProfileDir)
    {
        var rollbackDir = Path.Combine(modernProfileDir, RollbackFolderName);
        if (!Directory.Exists(rollbackDir))
        {
            return 0;
        }

        var restored = 0;
        foreach (var file in Directory.GetFiles(rollbackDir))
        {
            var dest = Path.Combine(modernProfileDir, Path.GetFileName(file));
            File.Copy(file, dest, overwrite: true);
            restored++;
        }
        return restored;
    }
}
