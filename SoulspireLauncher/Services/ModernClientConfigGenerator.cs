using System.IO;
using System.Security.Cryptography;
using System.Text;
using SoulspireLauncher.Models;

namespace SoulspireLauncher.Services;

/// <summary>
/// Generates isolated Modern (VanaCore / Soulspire Client) configuration and boot scripts under
/// ModernClient\ without ever mutating Ashita\ or retail FFXI Game\ files, and without ever
/// persisting plaintext passwords to disk.
/// </summary>
public sealed class ModernClientConfigGenerator
{
    public const string DefaultIniFileName = "vanacore.ini";
    public const string BootScriptRelativePath = @"scripts\boot.txt";
    public const string RollbackFolderName = ".rollback";

    public static ClientEngineMode ResolveEffectiveEngine(LauncherSettings settings, LauncherManifest? manifest)
    {
        if (settings.ClientEngine != ClientEngineMode.Modern)
        {
            return ClientEngineMode.Classic;
        }

        var normalizedChannel = ManifestUpdateService.NormalizeUserFacingChannel(settings.UpdateChannel);
        if (normalizedChannel == UpdateChannel.Testing)
        {
            return ClientEngineMode.Modern;
        }

        return manifest?.ModernClient?.ClientVerified == true
            ? ClientEngineMode.Modern
            : ClientEngineMode.Classic;
    }

    public static string GetAccountIniFileName(string? username)
    {
        if (string.IsNullOrWhiteSpace(username))
        {
            return DefaultIniFileName;
        }

        var normalized = username.Trim().ToLowerInvariant();
        var hash = SHA256.HashData(Encoding.UTF8.GetBytes(normalized));
        var prefix = Convert.ToHexString(hash)[..12].ToLowerInvariant();
        return $"vanacore.{prefix}.ini";
    }

    public static string BuildIniContent(
        LauncherSettings settings,
        string serverHost,
        string? polFolder,
        string? ffxiFolder)
    {
        var sb = new StringBuilder();
        sb.AppendLine("; Auto-generated by SoulspireXI Launcher for Modern Client (VanaCore).");
        sb.AppendLine("; SECURITY: Passwords are NEVER written to this file (passed via --password-stdin).");
        sb.AppendLine();
        sb.AppendLine("[client]");
        if (!string.IsNullOrWhiteSpace(polFolder))
        {
            sb.AppendLine($"pol={polFolder.Trim()}");
        }
        if (!string.IsNullOrWhiteSpace(ffxiFolder))
        {
            sb.AppendLine($"ffxi={ffxiFolder.Trim()}");
        }
        sb.AppendLine("attached=0");
        sb.AppendLine($"autoclose={(settings.AutoCloseOnLaunch ? 1 : 0)}");
        // Keep singlemenu=0 so menuwind Button ID 16 stays owned by Soulspire Native (BLK-013).
        sb.AppendLine("singlemenu=0");
        sb.AppendLine("packets.keepactions=1");
        sb.AppendLine();

        sb.AppendLine("[server]");
        sb.AppendLine($"server={serverHost.Trim()}");
        sb.AppendLine();

        sb.AppendLine("[logging]");
        sb.AppendLine("enabled=1");
        sb.AppendLine();

        sb.AppendLine("[addons]");
        sb.AppendLine("ashita.interface=4.30");
        sb.AppendLine("ashita.libs=4.30");
        sb.AppendLine("delay.login=1");
        sb.AppendLine();

        sb.AppendLine("[pivot]");
        var enablePivot = !settings.ModernClientSafeLoginMode && settings.EnablePivotOverlay;
        sb.AppendLine($"enabled={(enablePivot ? 1 : 0)}");
        sb.AppendLine("rootfolder=pivot");
        if (enablePivot)
        {
            sb.AppendLine();
            sb.AppendLine("[pivot.order]");
            sb.AppendLine("0=soulspirexi");
            if (settings.EnableFlintlockDualPistolsOverlay)
            {
                sb.AppendLine($"1={AshitaConfigGenerator.FlintlockOverlayFolderName}");
            }
        }
        sb.AppendLine();

        sb.AppendLine("[graphics]");
        sb.AppendLine($"api={(settings.ModernClientUseD3D11Fallback ? "d3d11" : "d3d12")}");
        if (settings.ModernClientSafeLoginMode)
        {
            // Phase 1 safe mode: disable optional rendering modifications for clean baseline login.
            sb.AppendLine("shadows=0");
            sb.AppendLine("ao=0");
            sb.AppendLine("water=0");
            sb.AppendLine("grass=0");
            sb.AppendLine("bloom=0");
            sb.AppendLine("godrays=0");
            sb.AppendLine("dof=0");
            sb.AppendLine("upscale=off");
        }
        sb.AppendLine();

        sb.AppendLine("[ffxi]");
        sb.AppendLine($"resolution.game={settings.WindowWidth}x{settings.WindowHeight}");
        sb.AppendLine($"resolution.ui={settings.MenuWidth}x{settings.MenuHeight}");
        sb.AppendLine($"hardwaremouse={(settings.HardwareMouse ? 1 : 0)}");
        sb.AppendLine();

        sb.AppendLine("[discord]");
        sb.AppendLine("enabled=0");

        return sb.ToString();
    }

    public static string BuildBootScriptContent(LauncherSettings settings)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Auto-generated by SoulspireXI Launcher for Modern Client (VanaCore).");
        if (settings.ModernClientSafeLoginMode)
        {
            sb.AppendLine("# Phase 1 Safe Login Mode: custom Soulspire native/addon hooks disabled.");
            sb.AppendLine("# Disable Safe Login Mode in Launcher Settings once baseline server login is verified.");
            return sb.ToString();
        }

        sb.AppendLine("# Progressive SoulspireXI Modern Client boot script.");
        sb.AppendLine("/plugin load soulspire_native");
        sb.AppendLine("/wait 1");
        if (settings.AutoLoadCrystalSocketAddon)
        {
            sb.AppendLine("/addon load crystalsocket ashita");
        }
        if (settings.AutoLoadSoulHudAddon || settings.AutoLoadTalentsAddon)
        {
            sb.AppendLine("/addon load soulspire_core ashita");
        }
        if (settings.AutoLoadFlintlockAddon)
        {
            sb.AppendLine("/addon load soulspire_flintlock ashita");
        }
        if (settings.AutoLoadGearAddon)
        {
            sb.AppendLine("/addon load soulspire_gear ashita");
        }
        return sb.ToString();
    }

    public string WriteAllConfigs(
        string modernClientDir,
        LauncherSettings settings,
        string serverHost,
        string? polFolder,
        string? ffxiFolder)
    {
        Directory.CreateDirectory(modernClientDir);
        Directory.CreateDirectory(Path.Combine(modernClientDir, "scripts"));
        Directory.CreateDirectory(Path.Combine(modernClientDir, "pivot"));
        Directory.CreateDirectory(Path.Combine(modernClientDir, "logs"));

        var iniFileName = GetAccountIniFileName(settings.Username);
        var iniPath = Path.Combine(modernClientDir, iniFileName);
        var bootPath = Path.Combine(modernClientDir, BootScriptRelativePath);

        File.WriteAllText(iniPath, BuildIniContent(settings, serverHost, polFolder, ffxiFolder), new UTF8Encoding(false));
        File.WriteAllText(bootPath, BuildBootScriptContent(settings), new UTF8Encoding(false));
        return iniFileName;
    }

    /// <summary>
    /// Snapshots existing ModernClient executables/DLLs to ModernClient\.rollback\ before updates
    /// so players can roll back cleanly without touching Classic Ashita v4.
    /// </summary>
    public static int CreateRollbackSnapshot(string modernClientDir)
    {
        if (string.IsNullOrWhiteSpace(modernClientDir) || !Directory.Exists(modernClientDir))
        {
            return 0;
        }

        var rollbackDir = Path.Combine(modernClientDir, RollbackFolderName);
        if (Directory.Exists(rollbackDir))
        {
            Directory.Delete(rollbackDir, recursive: true);
        }
        Directory.CreateDirectory(rollbackDir);

        var copied = 0;
        foreach (var name in new[] { "SoulspireClient.exe", "VanaCore.exe", "SoulspireClient.Core.dll", "VanaCore.Core.dll" })
        {
            var src = Path.Combine(modernClientDir, name);
            if (File.Exists(src))
            {
                File.Copy(src, Path.Combine(rollbackDir, name), overwrite: true);
                copied++;
            }
        }
        return copied;
    }

    public static int RestoreRollbackSnapshot(string modernClientDir)
    {
        var rollbackDir = Path.Combine(modernClientDir, RollbackFolderName);
        if (!Directory.Exists(rollbackDir))
        {
            return 0;
        }

        var restored = 0;
        foreach (var file in Directory.GetFiles(rollbackDir))
        {
            var dest = Path.Combine(modernClientDir, Path.GetFileName(file));
            File.Copy(file, dest, overwrite: true);
            restored++;
        }
        return restored;
    }
}
